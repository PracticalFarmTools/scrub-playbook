/** Sort any instrument array by Stringer Logic group order, then alphabetically within group */
export function sortByStringerLogic(instruments) {
  return [...instruments].sort((a, b) => {
    const ga = a.sortGroup || 5;
    const gb = b.sortGroup || 5;
    if (ga !== gb) return ga - gb;
    return a.name.localeCompare(b.name);
  });
}

